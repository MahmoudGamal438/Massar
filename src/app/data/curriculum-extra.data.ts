function q(
  id: string,
  title: string,
  lessonId: string,
  levelId: string,
  prompt: string,
  options: string[],
  correctIndex: number,
  explanation: string,
): Quiz {
  return {
    id,
    title,
    lessonId,
    levelId,
    passPercent: 70,
    questions: [{ id: 'q1', prompt, options, correctIndex, explanation }],
  };
}

